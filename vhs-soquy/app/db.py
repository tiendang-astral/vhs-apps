def startup_lock(db):
    """Khóa khi khởi động: nhiều worker / nhiều máy chủ cùng khởi động không tạo bảng, nạp dữ liệu trùng."""
    if IS_PG:
        db.execute('SELECT pg_advisory_xact_lock(7710001)')


DOC_TABLES = ('doc_cashbook', 'doc_partner_payment', 'doc_payroll', 'doc_cash_fund')
# Cột bổ sung cho CSDL đã tạo từ phiên bản trước (tự thêm khi khởi động)
MIGRATIONS = [(t, 'dir_by', 'BIGINT') for t in DOC_TABLES] + [(t, 'dir_at', 'TEXT') for t in DOC_TABLES]


def _columns(db, table):
    if IS_PG:
        return {r['column_name'] for r in db.all('SELECT column_name FROM information_schema.columns WHERE table_name=?', [table])}
    return {r['name'] for r in db.all(f'PRAGMA table_info({table})')}


def init_schema():
    with get_db() as db:
        startup_lock(db)
        for stmt in SCHEMA:
            db.execute(stmt)
        for table, col, typ in MIGRATIONS:
            if col not in _columns(db, table):
                db.execute(f'ALTER TABLE {table} ADD COLUMN {col} {typ}')
