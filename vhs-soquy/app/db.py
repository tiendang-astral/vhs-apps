"""Lớp truy cập CSDL mỏng, chạy được trên PostgreSQL (production) và SQLite (chạy thử / test).

- Viết SQL chuẩn với dấu hỏi `?` làm tham số; adapter tự đổi sang `%s` cho PostgreSQL.
- Ngày lưu dạng chuỗi ISO 'YYYY-MM-DD' (so sánh, sắp xếp đúng trên cả 2 CSDL).
- Số tiền lưu BIGINT (VND không có số lẻ) để chính xác tuyệt đối.
"""
import queue
import sqlite3
import threading
from contextlib import contextmanager
from pathlib import Path

from .config import settings

URL = settings.DATABASE_URL
IS_PG = URL.startswith('postgres')


class DB:
    """Một kết nối + transaction. Dùng qua `with get_db() as db:`."""

    def __init__(self, conn):
        self.conn = conn

    def _sql(self, sql):
        return sql.replace('?', '%s') if IS_PG else sql

    def execute(self, sql, params=()):
        cur = self.conn.cursor()
        cur.execute(self._sql(sql), tuple(params))
        return cur

    def all(self, sql, params=()):
        cur = self.execute(sql, params)
        rows = cur.fetchall()
        return [dict(r) for r in rows]

    def one(self, sql, params=()):
        cur = self.execute(sql, params)
        r = cur.fetchone()
        return dict(r) if r else None

    def scalar(self, sql, params=()):
        r = self.execute(sql, params).fetchone()
        if r is None:
            return None
        return list(dict(r).values())[0]

    def insert(self, table, data):
        cols = list(data.keys())
        sql = f'INSERT INTO {table} ({",".join(cols)}) VALUES ({",".join("?" * len(cols))}) RETURNING id'
        return self.scalar(sql, [data[c] for c in cols])

    def update(self, table, id_, data):
        if not data:
            return
        sets = ','.join(f'{c}=?' for c in data)
        self.execute(f'UPDATE {table} SET {sets} WHERE id=?', list(data.values()) + [id_])

    def executemany(self, sql, seq):
        cur = self.conn.cursor()
        cur.executemany(self._sql(sql), [tuple(p) for p in seq])


# ---------------------------------------------------------------- kết nối
class _Pool:
    def __init__(self, factory, size):
        self.factory, self.q = factory, queue.LifoQueue(maxsize=size)

    def get(self):
        try:
            return self.q.get_nowait()
        except queue.Empty:
            return self.factory()

    def put(self, conn):
        try:
            self.q.put_nowait(conn)
        except queue.Full:
            conn.close()


def _pg_factory():
    import psycopg
    from psycopg.rows import dict_row
    return psycopg.connect(URL, row_factory=dict_row, autocommit=False)


def _sqlite_factory():
    path = URL.replace('sqlite:///', '')
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(path, check_same_thread=False, timeout=30)
    conn.row_factory = sqlite3.Row
    conn.create_function('LOWER', 1, lambda v: v.lower() if isinstance(v, str) else v, deterministic=True)  # hỗ trợ tiếng Việt
    conn.execute('PRAGMA foreign_keys=ON')
    conn.execute('PRAGMA journal_mode=WAL')
    return conn


_pool = _Pool(_pg_factory if IS_PG else _sqlite_factory, settings.DB_POOL_SIZE)
_sqlite_lock = threading.Lock()   # SQLite: ghi tuần tự cho an toàn


@contextmanager
def get_db():
    conn = _pool.get()
    lock = None if IS_PG else _sqlite_lock
    if lock:
        lock.acquire()
    try:
        yield DB(conn)
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        if lock:
            lock.release()
        _pool.put(conn)


